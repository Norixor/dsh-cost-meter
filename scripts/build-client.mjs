// Builds client.js from src/client/.
//
// The host concatenates the bytes of `exports["./client"]` into one classic <script>, so the
// browser half has to be a single file with no top-level import/export. To keep each source
// file small and focused, the sources are plain fragments that this script glues together:
//
//   src/client/banner.txt      header comment (verbatim)
//   src/client/lib/*.js        factory scope, in file-name order (React helpers, components)
//   src/client/apply/*.js      apply(ctx) scope, in file-name order (slot registrations)
//
// A fragment may use `export` so the same file can be imported by tests as an ES module;
// the keyword is stripped when the fragment is inlined. Fragments must not import anything
// and must not contain multi-line template literals (they would be re-indented).
//
// Usage: node scripts/build-client.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'src', 'client')
const OUT = join(ROOT, 'client.js')

const GENERATED = '// GENERATED by scripts/build-client.mjs from src/client/ — edit the sources, then run `npm run build`.'

function fragments(dir) {
  return readdirSync(join(SRC, dir)).filter((name) => name.endsWith('.js')).sort().map((name) => ({
    name: dir + '/' + name,
    text: readFileSync(join(SRC, dir, name), 'utf8'),
  }))
}

/** Strip the module-only `export` keyword and indent every non-empty line. */
function inline(fragment, spaces) {
  const pad = ' '.repeat(spaces)
  if (/^\s*import\s/m.test(fragment.text)) throw new Error(fragment.name + ': fragments must not import')
  return fragment.text
    .replace(/^export\s+(?=(async\s+)?(function|const|let|class)\b)/gm, '')
    .replace(/\s+$/, '')
    .split('\n')
    .map((line) => (line === '' ? '' : pad + line))
    .join('\n')
}

export function buildClient() {
  const banner = readFileSync(join(SRC, 'banner.txt'), 'utf8').replace(/\s+$/, '')
  const lib = fragments('lib').map((f) => inline(f, 6)).join('\n\n')
  const apply = fragments('apply').map((f) => inline(f, 10)).join('\n\n')
  return [
    banner,
    GENERATED,
    "if (typeof window !== 'undefined' && typeof window.__ModuleLoader__ !== 'undefined') {",
    '  window.__ModuleLoader__.load({',
    "    id: '@norixor/dsh-cost-meter',",
    '    factory(require) {',
    lib,
    '',
    '      return {',
    "        inject: ['slots', 'locale'],",
    '        apply(ctx) {',
    apply,
    '        },',
    '      }',
    '    },',
    '  })',
    '}',
    '',
  ].join('\n')
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const next = buildClient()
  if (process.argv.includes('--check')) {
    let current = ''
    try { current = readFileSync(OUT, 'utf8') } catch { /* missing counts as stale */ }
    if (current !== next) {
      console.error('client.js is out of date — run `npm run build`')
      process.exit(1)
    }
    console.log('client.js is up to date')
  } else {
    writeFileSync(OUT, next)
    console.log('wrote client.js (' + next.split('\n').length + ' lines)')
  }
}
